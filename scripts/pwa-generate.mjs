#!/usr/bin/env node
/**
 * SG16 PWA generator — one config per project, regenerate before deploy.
 * Usage: node generate.mjs <project-root>
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const projectRoot = path.resolve(process.argv[2] || process.cwd());
const configPath = path.join(projectRoot, 'pwa.config.json');

if (!fs.existsSync(configPath)) {
  console.error(`Missing pwa.config.json in ${projectRoot}`);
  process.exit(1);
}

const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const version = String(config.version ?? 1);
const cacheName = `${config.id}-v${version}`;

function write(relPath, content) {
  const out = path.join(projectRoot, relPath);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, content);
  console.log(`  wrote ${relPath}`);
}

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

function buildManifest() {
  const manifest = {
    id: config.manifest_id || config.scope || '/',
    name: config.name,
    short_name: config.short_name,
    description: config.description,
    start_url: config.start_url || '/',
    scope: config.scope || '/',
    display: config.display || 'standalone',
    orientation: config.orientation || 'any',
    background_color: config.background_color,
    theme_color: config.theme_color,
    lang: config.lang || 'en',
    dir: config.dir || 'ltr',
    categories: config.categories || [],
    icons: [
      {
        src: `/${(config.icons?.any_192 || 'assets/icons/icon-192.png').replace(/^\//, '')}`,
        sizes: '192x192',
        type: 'image/png',
        purpose: 'any',
      },
      {
        src: `/${(config.icons?.any_512 || 'assets/icons/icon-512.png').replace(/^\//, '')}`,
        sizes: '512x512',
        type: 'image/png',
        purpose: 'any',
      },
      {
        src: `/${(config.icons?.maskable_512 || 'assets/icons/icon-512-maskable.png').replace(/^\//, '')}`,
        sizes: '512x512',
        type: 'image/png',
        purpose: 'maskable',
      },
    ],
  };

  if (Array.isArray(config.shortcuts) && config.shortcuts.length) {
    manifest.shortcuts = config.shortcuts
      .filter((s) => !String(s.url).startsWith('http'))
      .map((s) => ({
        name: s.name,
        short_name: s.short_name || s.name,
        description: s.description,
        url: s.url,
        icons: s.icon
          ? [{ src: `/${String(s.icon).replace(/^\//, '')}`, sizes: '96x96', type: 'image/png' }]
          : undefined,
      }));
  }

  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function buildSw() {
  const precache = JSON.stringify(config.precache || ['/', '/manifest.webmanifest'], null, 2);
  return `/* Generated by shared/sg16-pwa — do not edit by hand. */
const CACHE = '${cacheName}';
const PRECACHE = ${precache};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

function isHtmlRequest(request, url) {
  if (request.mode === 'navigate') return true;
  if (url.pathname === '/sw.js') return true;
  if (/\\.html?$/.test(url.pathname)) return true;
  const accept = request.headers.get('accept') || '';
  return accept.includes('text/html');
}

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  if (isHtmlRequest(event.request, url)) {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() =>
          caches.match(event.request).then((cached) => cached || caches.match('${config.start_url || '/'}'))
        )
    );
    return;
  }

  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => cached);

      return cached || network;
    })
  );
});
`;
}

function buildPwaJs() {
  return `if ('serviceWorker' in navigator) {
  let refreshing = false;

  navigator.serviceWorker.addEventListener('controllerchange', () => {
    if (refreshing) return;
    refreshing = true;
    window.location.reload();
  });

  function activateWaitingWorker(reg) {
    if (reg.waiting) {
      reg.waiting.postMessage({ type: 'SKIP_WAITING' });
    }
  }

  async function registerSw() {
    try {
      const reg = await navigator.serviceWorker.register('/sw.js');

      reg.addEventListener('updatefound', () => {
        const worker = reg.installing;
        if (!worker) return;
        worker.addEventListener('statechange', () => {
          if (worker.state === 'installed' && navigator.serviceWorker.controller) {
            activateWaitingWorker(reg);
          }
        });
      });

      activateWaitingWorker(reg);

      async function checkForUpdate() {
        try {
          await reg.update();
        } catch {
          /* offline or blocked */
        }
      }

      checkForUpdate();
      setInterval(checkForUpdate, 60 * 1000);
      document.addEventListener('visibilitychange', () => {
        if (document.visibilityState === 'visible') checkForUpdate();
      });
      window.addEventListener('focus', checkForUpdate);
    } catch {
      /* SW unsupported or blocked */
    }
  }

  window.addEventListener('load', registerSw);
}
`;
}

function generateIcons() {
  if (!config.icon_source) return;
  const srcPath = path.join(projectRoot, config.icon_source);
  if (!fs.existsSync(srcPath)) {
    console.warn(`  skip icons — missing ${config.icon_source}`);
    return;
  }

  const iconsDir = path.join(projectRoot, config.icons_dir || 'assets/icons');
  fs.mkdirSync(iconsDir, { recursive: true });
  const bg = hexToRgb(config.icon_background || config.background_color || '#000000');

  if (config.icon_source.toLowerCase().endsWith('.svg')) {
    const scriptPath = path.join(iconsDir, '.generate-badge-icons.py');
    const label = (config.short_name || config.id || 'SG16').slice(0, 8);
    const sub = (config.icon_badge_sub || '').slice(0, 10);
    fs.writeFileSync(
      scriptPath,
      `# auto-generated badge icons (SVG source)
from PIL import Image, ImageDraw, ImageFont
import os
out = ${JSON.stringify(iconsDir)}
bg = tuple(${JSON.stringify(bg)})
label = ${JSON.stringify(label)}
sub = ${JSON.stringify(sub)}

def badge(size):
    img = Image.new('RGB', (size, size), bg)
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype('arialbd.ttf', max(12, int(size * 0.22)))
        font2 = ImageFont.truetype('arial.ttf', max(10, int(size * 0.12)))
    except Exception:
        font = ImageFont.load_default()
        font2 = font
    tw = d.textlength(label, font=font) if hasattr(d, 'textlength') else size * 0.5
    d.text(((size - tw) / 2, size * 0.36), label, fill='white', font=font)
    if sub:
        sw = d.textlength(sub, font=font2) if hasattr(d, 'textlength') else size * 0.4
        d.text(((size - sw) / 2, size * 0.58), sub, fill='#C76A16', font=font2)
    return img

for size, name in [(192, 'icon-192.png'), (512, 'icon-512.png'), (512, 'icon-512-maskable.png')]:
    badge(size).save(os.path.join(out, name), 'PNG')
`,
    );
    execFileSync('python', [scriptPath], { stdio: 'inherit' });
    fs.unlinkSync(scriptPath);
    console.log('  badge icons generated (svg source)');
  } else {
  const scriptPath = path.join(iconsDir, '.generate-icons.py');
  fs.writeFileSync(
    scriptPath,
    `# auto-generated
from PIL import Image
import os
src = ${JSON.stringify(srcPath)}
out = ${JSON.stringify(iconsDir)}
bg = ${JSON.stringify(bg)}
bg_rgba = tuple(bg) + (255,)
img = Image.open(src).convert('RGBA')
w, h = img.size
side = max(w, h)
canvas = Image.new('RGBA', (side, side), bg_rgba)
canvas.paste(img, ((side - w) // 2, (side - h) // 2), img)
for size, name in [(192, 'icon-192.png'), (512, 'icon-512.png')]:
    canvas.resize((size, size), Image.LANCZOS).convert('RGB').save(os.path.join(out, name), 'PNG')
inner = canvas.resize((int(512 * 0.72), int(512 * 0.72)), Image.LANCZOS)
mask = Image.new('RGB', (512, 512), tuple(bg))
mask.paste(inner, ((512 - inner.size[0]) // 2, (512 - inner.size[1]) // 2), inner)
mask.save(os.path.join(out, 'icon-512-maskable.png'), 'PNG')
`,
  );

  execFileSync('python', [scriptPath], { stdio: 'inherit' });
  fs.unlinkSync(scriptPath);
  console.log('  icons generated');
  }

  if (Array.isArray(config.icon_exports)) {
    for (const exp of config.icon_exports) {
      const from = path.join(projectRoot, exp.from);
      const to = path.join(projectRoot, exp.to);
      if (fs.existsSync(from)) {
        fs.mkdirSync(path.dirname(to), { recursive: true });
        fs.copyFileSync(from, to);
        console.log(`  copied ${exp.from} → ${exp.to}`);
      }
    }
  }
}

console.log(`SG16 PWA generate: ${config.id} (${config.domain || 'local'}) v${version}`);

const forceIcons = process.argv.includes('--force-icons');
if (!forceIcons && config.icons_commit) {
  console.log('  skip icons (icons_commit — run with --force-icons to regenerate)');
} else {
  generateIcons();
}

write(config.outputs?.manifest || 'manifest.webmanifest', buildManifest());
write(config.outputs?.sw || 'sw.js', buildSw());
write(config.outputs?.pwa_js || 'js/pwa.js', buildPwaJs());

console.log('Done. Bump pwa.config.json "version" when precache paths change.');
